_start_memory_monitor() {
    local tc=$1
    local interval="${E2E_MEMORY_MONITOR_SEC:-0}"
    [ "$interval" -gt 0 ] 2>/dev/null || return

    local log="$LOG_BASE/memory_tc${tc}.log"
    (
        while true; do
            date '+[MEMORY] %FT%T%z'
            free -b
            ps -eo pid=,ppid=,rss=,vsz=,comm= | \
                while read -r pid ppid rss vsz comm; do
                    case "$comm" in
                        gem5.opt|ubio|networksim)
                            printf '[MEMORY-PROC] pid=%s ppid=%s rss_kb=%s vsz_kb=%s cmd=%s\n' \
                                "$pid" "$ppid" "$rss" "$vsz" "$comm"
                            ;;
                    esac
                done
            sleep "$interval"
        done
    ) >>"$log" 2>&1 &
    MEMORY_MONITOR_PID=$!
    echo "[monitor] memory sampling every ${interval}s -> $log"
}

# Return the greatest recent UBIO simulation tick.  Guest phase markers are
# sparse during long spill streams, so simout byte growth alone is not a
# liveness signal; protocol tick movement is.  Only inspect each log tail to
# keep the supervisor's own work bounded as logs grow.
_aggregate_protocol_tick() {
    local max_tick=0
    local stream log tick
    for nid in $(seq 0 $((NUM_NODES-1))); do
        for sid in $(seq 0 $((NUM_SOCKETS-1))); do
            for stream in stdout.log stderr.log; do
                log="$LOG_BASE/ubio_tc${tc}_n${nid}_s${sid}/$stream"
                [ -f "$log" ] || continue
                tick=$(perl -e '
                    $f = shift;
                    open(my $fh, "<", $f) or exit;
                    $n = -s $fh;
                    seek($fh, $n > 1048576 ? $n - 1048576 : 0, 0);
                    local $/;
                    $s = <$fh>;
                    while ($s =~ /tick=(\d+)/g) { $last = $1; }
                    print $last // 0;
                ' "$log")
                if [ "$tick" -gt "$max_tick" ] 2>/dev/null; then
                    max_tick=$tick
                fi
            done
        done
    done
    printf '%s\n' "$max_tick"
}

# ── Supervisor: opt-in long-run watchdog ───────────────────────────
# Writes PID manifest, monitors liveness/progress/log-size/disk.
# On fault: writes reason to status file, kills CURRENT_TC PIDs + self;
# never uses pkill.  Returns non-zero to signal runner failure.
_supervisor_start() {
    local tc="$1"
    local m5outdir="$2"
    local num_nodes="$3"
    local manifest="$LOG_BASE/supervisor_manifest_tc${tc}.txt"
    local status_file="$LOG_BASE/supervisor_status_tc${tc}.txt"
    local gem5_pids="$GEM5_PIDS"
    local ubio_pids="$UBIO_PIDS"
    local nsim_pid="$NSIM_PID"

    # Write PID manifest
    {
        echo "# Supervisor manifest TC${tc} $(date -Iseconds)"
        echo "RUNNER_PID=$$"
        echo "NSIM_PID=$nsim_pid"
        echo "GEM5_PIDS=$gem5_pids"
        echo "UBIO_PIDS=$ubio_pids"
        echo "NUM_NODES=$num_nodes"
        echo "LOG_BASE=$LOG_BASE"
        echo "M5OUTDIR=$m5outdir"
        echo "LOG_CEIL_GB=$EP_SUPERVISOR_LOG_CEIL_GB"
        echo "DISK_FREE_GB=$EP_SUPERVISOR_DISK_FREE_GB"
        echo "INTERVAL=$EP_SUPERVISOR_INTERVAL"
        echo "PROGRESS_STALL_SEC=$EP_SUPERVISOR_PROGRESS_STALL_SEC"
        echo "TRACE_PERF=$EP_TRACE_PERF first_n=$EP_TRACE_PERF_FIRST_N every=$EP_TRACE_PERF_EVERY max=$EP_TRACE_PERF_MAX"
        echo "PORT_HWM=$EP_PORT_HWM NSIM_MAX_PENDING=$EP_NSIM_MAX_PENDING"
    } > "$manifest"

    # Start background monitor
    (
        local interval="$EP_SUPERVISOR_INTERVAL"
        local ceil_bytes=$((EP_SUPERVISOR_LOG_CEIL_GB * 1073741824))
        local floor_bytes=$((EP_SUPERVISOR_DISK_FREE_GB * 1073741824))
        local prev_guest_progress=-1
        local prev_protocol_tick=-1
        local guest_stall_count=0
        local protocol_stall_count=0
        local stall_limit=$((EP_SUPERVISOR_PROGRESS_STALL_SEC / interval))
        [ "$stall_limit" -gt 0 ] 2>/dev/null || stall_limit=1

        while true; do
            sleep "$interval"

            # ── 1. Liveness: live gem5 plus clean completed peers ─
            local alive_count=0
            local completed_count=0
            for pid in $gem5_pids; do
                local state
                state=$(ps -o stat= -p "$pid" 2>/dev/null || true)
                state=${state#${state%%[![:space:]]*}}
                case "$state" in
                    Z*|"") completed_count=$((completed_count + 1)) ;;
                    *) if [ -n "$state" ]; then alive_count=$((alive_count + 1)); fi ;;
                esac
            done
            local gem5_status gem5_code
            for gem5_status in "$LOG_BASE"/child_status_tc${tc}/gem5_node*.exit; do
                [ -f "$gem5_status" ] || continue
                gem5_code=$(tr -d '[:space:]' <"$gem5_status")
                if [ "$gem5_code" != "0" ]; then
                    local ts; ts=$(date +%s)
                    echo "FAULT ${ts} gem5_exit: $(basename "$gem5_status")=$gem5_code" >> "$status_file"
                    echo "[supervisor] FAULT: $(basename "$gem5_status") exited $gem5_code"
                    for pid in $gem5_pids $ubio_pids $nsim_pid; do
                        kill -9 "$pid" 2>/dev/null || true
                    done
                    exit 1
                fi
            done
            # All gem5 wrappers exiting cleanly means the foreground runner is
            # about to collect statuses and coordinate UBIO/networksim teardown.
            if [ "$alive_count" -eq 0 ]; then
                local ts; ts=$(date +%s)
                echo "COMPLETE ${ts} all_gem5_exited; runner collecting statuses" >> "$status_file"
                exit 0
            fi

            # ── 2. Progress: either guest output or protocol tick movement
            # keeps the generic watchdog alive. Profile-specific runners may
            # inspect both fields to distinguish guest stalls from long fault
            # recovery or spill streams without killing valid workloads.
            local current_guest_progress=0
            for nid in $(seq 0 $((num_nodes - 1))); do
                local pf="$m5outdir/node${nid}/simout_n${nid}"
                if [ -f "$pf" ]; then
                    current_guest_progress=$((current_guest_progress + $(stat -c %s "$pf" 2>/dev/null || echo 0)))
                fi
            done
            local current_protocol_tick
            current_protocol_tick=$(_aggregate_protocol_tick)
            if [ "$current_guest_progress" -ne "$prev_guest_progress" ] || \
               [ "$current_protocol_tick" -gt "$prev_protocol_tick" ]; then
                prev_guest_progress="$current_guest_progress"
                prev_protocol_tick="$current_protocol_tick"
                guest_stall_count=0
            else
                guest_stall_count=$((guest_stall_count + 1))
                if [ "$guest_stall_count" -ge "$stall_limit" ]; then
                    local ts; ts=$(date +%s)
                    echo "FAULT ${ts} progress_stall: guest_bytes=${current_guest_progress} protocol_tick=${current_protocol_tick} for $((guest_stall_count * interval))s" >> "$status_file"
                    echo "[supervisor] FAULT: no guest or protocol tick progress for $((guest_stall_count * interval))s"
                    for pid in $gem5_pids $ubio_pids $nsim_pid; do
                        kill -9 "$pid" 2>/dev/null || true
                    done
                    exit 1
                fi
            fi
            if [ "$current_protocol_tick" -gt "$prev_protocol_tick" ]; then
                protocol_stall_count=0
            else
                protocol_stall_count=$((protocol_stall_count + 1))
            fi

            # ── 3. Log directory size check ───────────────────────
            local log_size
            log_size=$(du -sb "$LOG_BASE" 2>/dev/null | cut -f1 || echo 0)
            if [ "$log_size" -gt "$ceil_bytes" ]; then
                local ts; ts=$(date +%s)
                echo "FAULT ${ts} log_size: ${log_size} bytes > ceil ${ceil_bytes} bytes (${EP_SUPERVISOR_LOG_CEIL_GB}GiB)" >> "$status_file"
                echo "[supervisor] FAULT: log dir ${log_size} > ${EP_SUPERVISOR_LOG_CEIL_GB}GiB ceiling"
                for pid in $gem5_pids $ubio_pids $nsim_pid; do
                    kill -9 "$pid" 2>/dev/null || true
                done
                exit 1
            fi

            # ── 4. Disk free space check ──────────────────────────
            local disk_free
            disk_free=$(df -B1 "$LOG_BASE" 2>/dev/null | tail -1 | awk '{print $4}')
            if [ -n "$disk_free" ] && [ "$disk_free" -lt "$floor_bytes" ]; then
                local ts; ts=$(date +%s)
                echo "FAULT ${ts} disk_free: ${disk_free} bytes < floor ${floor_bytes} bytes (${EP_SUPERVISOR_DISK_FREE_GB}GiB)" >> "$status_file"
                echo "[supervisor] FAULT: disk free ${disk_free} < ${EP_SUPERVISOR_DISK_FREE_GB}GiB floor"
                for pid in $gem5_pids $ubio_pids $nsim_pid; do
                    kill -9 "$pid" 2>/dev/null || true
                done
                exit 1
            fi

            # ── Heartbeat (only to status file, not stdout) ───────
            local ts; ts=$(date +%s)
            echo "OK ${ts} alive=${alive_count}/${num_nodes} completed=${completed_count} guest_bytes=${current_guest_progress} guest_stall_sec=$((guest_stall_count * interval)) protocol_tick=${current_protocol_tick} protocol_stall_sec=$((protocol_stall_count * interval)) log_size=${log_size} disk_free=${disk_free:-na}" >> "$status_file"
        done
    ) &
    SUPERVISOR_PID=$!
    echo "[supervisor] started pid=$SUPERVISOR_PID manifest=$manifest interval=${EP_SUPERVISOR_INTERVAL}s"
}

_supervisor_stop() {
    if [ -n "${SUPERVISOR_PID:-}" ]; then
        kill "$SUPERVISOR_PID" 2>/dev/null || true
        SUPERVISOR_PID=""
    fi
}

run_tc() {
    local tc=$1
    CURRENT_TC=$tc
    export E2E_TC="$tc"
    : >"$LOG_BASE/launch_commands_tc${tc}.jsonl"
    _kill_infra  # ensure clean state before each TC

    # TC98 fix: per-TC timeout override.  High-contention tests need much
    # longer than the default 600s because PDES serialization is inherent.
    local TC_TIMEOUT="$TIMEOUT_SEC"
    case "$tc" in
        98) TC_TIMEOUT="${TIMEOUT_SEC_TC98:-1500}" ;;  # floor 1500s, overridable
        128) TC_TIMEOUT="${TIMEOUT_SEC_TC128:-1800}" ;; # full cache sweep + onload
        131) TC_TIMEOUT="${TIMEOUT_SEC_TC131:-7200}" ;;
        132) TC_TIMEOUT="${TIMEOUT_SEC_TC132:-7200}" ;;
        133) TC_TIMEOUT="${TIMEOUT_SEC_TC133:-7200}" ;;
        134) TC_TIMEOUT="${TIMEOUT_SEC_TC134:-7200}" ;;
        160) TC_TIMEOUT="${TIMEOUT_SEC_TC160:-1800}" ;;
    esac
    # Always respect a higher value passed via TIMEOUT_SEC env var
    if [ "$TIMEOUT_SEC" -gt "$TC_TIMEOUT" ] 2>/dev/null; then
        TC_TIMEOUT="$TIMEOUT_SEC"
    fi

    local m5base="$RUN_DIR/tc${tc}"
    local m5outdir="$m5base/m5out"
    local child_status_dir="$LOG_BASE/child_status_tc${tc}"
    rm -rf "$m5base"; mkdir -p "$m5outdir"
    rm -rf "$child_status_dir"; mkdir -p "$child_status_dir"

    echo ""
    echo "=== TC${tc} (topo=$TOPO_KIND, ${NUM_NODES}nodes x ${NUM_SOCKETS}sockets) ==="

    # 1. Compile workload into this run's private ELF path.
    local pressure_cflags="${WORKLOAD_CFLAGS:-}"
    if [ "$EP_L3_PRESSURE_TARGET_LINES" -gt 0 ] && [ "$tc" -ge 228 ] && [ "$tc" -le 235 ]; then
        pressure_cflags="$pressure_cflags -DL3_PRESSURE_LEVEL=$L3_PRESSURE_LEVEL"
        pressure_cflags="$pressure_cflags -DL3_PRESSURE_TARGET_LINES_OVERRIDE=$EP_L3_PRESSURE_TARGET_LINES"
        pressure_cflags="$pressure_cflags -DL3_PRESSURE_CACHE_LINES=$EP_L3_CACHE_LINES"
        pressure_cflags="$pressure_cflags -DL3_PRESSURE_SETS=$EP_L3_SETS"
        pressure_cflags="$pressure_cflags -DL3_PRESSURE_SEED=$METRIC3_L3_SEED"
        pressure_cflags="$pressure_cflags -DL3_DIRECTORY_PRESSURE_LINES=$L3_DIRECTORY_PRESSURE_LINES"
    fi
    NUM_NODES="$NUM_NODES" NUM_SOCKETS="$NUM_SOCKETS" WORKLOAD_CFLAGS="$pressure_cflags" \
        WORKLOAD_OUT="$WORKLOAD" bash "$ROOT_DIR/scripts/compile_workload.sh" "$tc" >/dev/null 2>&1 \
        || { echo "  TC${tc} COMPILE FAILED"; return 1; }

    # 2. Generate networksim topo.json (full mesh, --nodes/--sockets from JSON)
    python3 "$ROOT_DIR/scripts/gen_topo.py" --nodes "$NUM_NODES" --sockets "$NUM_SOCKETS" --out "$TOPO_JSON" >/dev/null 2>&1
    # Clean only this run's IPC endpoints. Other runs use distinct directories.
    rm -rf "$IPC_DIR" 2>/dev/null || true
    mkdir -p "$IPC_DIR"

    # 3. Start networksim (must bind before ubio connects)
    local nsim_pid_file="$child_status_dir/networksim.pid"
    rm -f "$nsim_pid_file"
    echo "[launch] networksim (NMOD=$NMOD)"
    local nsim_extra_args=()
    if [ "${NSIM_TRACE_ALL_FORWARDED:-0}" = "1" ]; then
        nsim_extra_args+=(--trace-all-forwarded)
    fi
    local nsim_cmd
    printf -v nsim_cmd '%q ' "$NSIM_BIN" "$TOPO_JSON" "$NUM_NODES" "$NUM_SOCKETS" "${nsim_extra_args[@]}"
    nsim_cmd="${nsim_cmd% }"
    record_launch_command "$tc" networksim "" "" "$nsim_cmd"
    (
      set +e
      "$NSIM_BIN" "$TOPO_JSON" "$NUM_NODES" "$NUM_SOCKETS" \
          "${nsim_extra_args[@]}" \
          >"$LOG_BASE/nsim_tc${tc}.log" 2>&1 &
      local_nsim_child=$!
      printf '%s\n' "$local_nsim_child" >"$nsim_pid_file"
      wait "$local_nsim_child"
      status=$?
      printf '%s\n' "$status" >"$child_status_dir/networksim.exit"
      exit "$status"
    ) &
    NSIM_PID=$!
    NSIM_CHILD_PID=""
    for _ in $(seq 1 50); do
        if [ -f "$nsim_pid_file" ]; then
            NSIM_CHILD_PID=$(tr -d '[:space:]' <"$nsim_pid_file")
            break
        fi
        sleep 0.1
    done
    if [ -z "$NSIM_CHILD_PID" ]; then
        echo "[launch] networksim failed to report child PID"
        _kill_infra
        return 1
    fi
    sleep 1
    if ! kill -0 "$NSIM_PID" 2>/dev/null; then
        local nsim_status="unknown"
        [ -f "$child_status_dir/networksim.exit" ] && \
            nsim_status=$(tr -d '[:space:]' <"$child_status_dir/networksim.exit")
        echo "[launch] networksim exited during startup (status=$nsim_status)"
        _kill_infra
        return 1
    fi

    # 4. Start N*K ubio processes before gem5. This gives every gem5 tick-zero
    # heartbeat a bound peer and avoids same-tick startup starvation.
    UBIO_PIDS=""
    local frules; frules="$(fault_rules_for_tc "$tc")"
    if [ -n "${UBIO_FAULT_RULES_APPEND:-}" ]; then
        [ -n "$frules" ] && frules="$frules;"
        frules="${frules}${UBIO_FAULT_RULES_APPEND}"
    fi
    if [ "$OURCC_CLEAR_PROFILE" = "lossless-oneway" ] && [[ "$frules" == *":ClearReq:"* ]]; then
        echo "FATAL: TC${tc} injects ClearReq faults but lossless-oneway assumes eventual delivery" >&2
        return 1
    fi
    local frargs=""
    [ -n "$frules" ] && frargs="--fault-rules=$frules"
    [ -n "$frules" ] && echo "[launch] fault rules (TC${tc}): $frules"
    local uextra; uextra="$(ubio_extra_args_for_tc "$tc")"
    if [ "$EP_HA_PROFILE" = "ha-vi" ]; then
        uextra="$uextra --home-controller=ha-vi --ha-exact-bytes=$HA_EXACT_BYTES"
        uextra="$uextra --ha-max-active=$HA_MAX_ACTIVE --ha-max-queue=$HA_MAX_QUEUE"
    fi
    uextra="$uextra --metadata-dram-bytes=${UBCC_METADATA_SIZE}"
    [ -n "$uextra" ] && echo "[launch] ubio extra args (TC${tc}): $uextra"
    for nid in $(seq 0 $((NUM_NODES-1))); do
        for sid in $(seq 0 $((NUM_SOCKETS-1))); do
            local mod_id="ubio_${nid}_s${sid}"
            local cmd
            if python3 -c "import json,sys;sys.exit(0 if any(m['id']==sys.argv[1] for m in json.load(open('$JSON'))['modules']) else 1)" "$mod_id" 2>/dev/null; then
                cmd="$(expand_cmd "$mod_id" "$frargs" "$uextra")"
            else
                cmd="$(expand_cmd "ubio_${nid}" "$frargs" "$uextra")"
            fi
            local logdir="$LOG_BASE/ubio_tc${tc}_n${nid}_s${sid}"
            mkdir -p "$logdir"
            record_launch_command "$tc" ubio "$nid" "$sid" "$cmd"
            ( set +e; eval "$cmd" 2>"$logdir/stderr.log" >"$logdir/stdout.log"; status=$?; \
              printf '%s\n' "$status" >"$child_status_dir/ubio_n${nid}_s${sid}.exit"; exit "$status" ) &
            UBIO_PIDS="$UBIO_PIDS $!"
        done
    done
    local n_ubio; n_ubio=$(echo $UBIO_PIDS | wc -w)
    echo "[launch] waiting for $n_ubio ubio receive ports..."
    local ubio_index=0 ubio_pid ubio_nid ubio_sid ubio_exit
    for ubio_pid in $UBIO_PIDS; do
        ubio_nid=$((ubio_index / NUM_SOCKETS))
        ubio_sid=$((ubio_index % NUM_SOCKETS))
        local ubio_log="$LOG_BASE/ubio_tc${tc}_n${ubio_nid}_s${ubio_sid}/stdout.log"
        local ubio_ready=0
        for _ in $(seq 1 300); do
            if grep -q '\[UBIO-IPC\]' "$ubio_log" 2>/dev/null; then
                ubio_ready=1
                break
            fi
            if ! kill -0 "$ubio_pid" 2>/dev/null; then
                break
            fi
            sleep 1
        done
        ubio_exit="$child_status_dir/ubio_n${ubio_nid}_s${ubio_sid}.exit"
        if [ "$ubio_ready" -ne 1 ]; then
            local ubio_status="unknown"
            [ -f "$ubio_exit" ] && \
                ubio_status=$(tr -d '[:space:]' <"$ubio_exit")
            echo "[launch] ubio node=$ubio_nid socket=$ubio_sid not ready (status=$ubio_status)"
            _kill_infra
            return 1
        fi
        echo "[launch]   ubio node=$ubio_nid socket=$ubio_sid ready"
        ubio_index=$((ubio_index + 1))
    done

    # 5. Start N gem5 nodes, wait until each binds its ports (STEP5 marker)
    GEM5_PIDS=""; local gem5_arr=()
    for nid in $(seq 0 $((NUM_NODES-1))); do
        local gdir="$LOG_BASE/gem5_tc${tc}_node${nid}"
        local node_od="$m5outdir/node${nid}"
        mkdir -p "$gdir" "$node_od"
        local cmd
        cmd="$(expand_cmd gem5_${nid} '' '' "$node_od")"
        cmd="$cmd --l3-size=$EP_L3_SIZE --l3-assoc=$EP_L3_ASSOC"
        # Optional per-node gem5 tracing for long-running E2E diagnosis.
        # Keep the debug stream separate from stderr so runner diagnostics stay usable.
        if [ -n "${GEM5_DEBUG_FLAGS:-}" ]; then
            local debug_args="--debug-flags=${GEM5_DEBUG_FLAGS} --debug-file=$gdir/gem5_debug.log"
            if [ -n "${GEM5_DEBUG_START:-}" ]; then
                debug_args="$debug_args --debug-start=${GEM5_DEBUG_START}"
            fi
            cmd="$GEM5_BIN $debug_args${cmd#"$GEM5_BIN"}"
        fi
        if [ "$tc" = "130" ] || [ "$tc" = "132" ] || [ "$tc" = "133" ] || [ "$tc" = "134" ] || [ "$tc" = "141" ] ||
           { [ "$tc" -ge 135 ] && [ "$tc" -le 139 ]; } ||
           { [ "$tc" -ge 142 ] && [ "$tc" -le 147 ]; }; then
            # These tests isolate directory policy; do not mix protocol optimizations.
            case "${EP_PERF_PROFILE:-spill-noopt}" in
                optimized) cmd="$cmd --silent-upgrade=1 --direct-fwd=0 --ubcc-batch-rs=1" ;;
                *)         cmd="$cmd --silent-upgrade=0 --direct-fwd=0 --ubcc-batch-rs=0" ;;
            esac
        elif [ "$tc" = "131" ]; then
            # TC131 is the capacity/latency comparison workload.  The baseline
            # is naive with every latency optimization disabled; optimized uses
            # spill and enables the latency optimization profile.
            case "${EP_PERF_PROFILE:-baseline}" in
                optimized) cmd="$cmd --silent-upgrade=1 --direct-fwd=0 --ubcc-batch-rs=1" ;;
                *)         cmd="$cmd --silent-upgrade=0 --direct-fwd=0 --ubcc-batch-rs=0" ;;
            esac
        elif [ "$tc" = "120" ] || [ "$tc" = "121" ] || [ "$tc" = "122" ] || [ "$tc" = "123" ] || [ "$tc" = "124" ] || [ "$tc" = "140" ]; then
            local default_profile=optimized
            if [ "$tc" = "140" ]; then default_profile=spill-noopt; fi
            case "${EP_PERF_PROFILE:-$default_profile}" in
                baseline|spill-noopt)
                    cmd="$cmd --silent-upgrade=0 --direct-fwd=0 --ubcc-batch-rs=0"
                    ;;
                optimized|*)
                    cmd="$cmd --silent-upgrade=1 --direct-fwd=0 --ubcc-batch-rs=1"
                    ;;
            esac
        fi
        # Explicit experiment-only gem5 flags, for example
        # EP_GEM5_OPTS='--silent-upgrade=1'. Normal test profiles above remain
        # authoritative unless this variable is intentionally set by a runner.
        if [ -n "${EP_GEM5_OPTS:-}" ]; then
            cmd="$cmd ${EP_GEM5_OPTS}"
        fi
        # Phase 0: propagate metadata DRAM capacity to gem5 config
        cmd="$cmd --ubcc_metadata_size=${UBCC_METADATA_SIZE}"
        cmd="$cmd --ha-profile=${EP_HA_PROFILE}"
        cmd="$cmd --clear-profile=${OURCC_CLEAR_PROFILE}"
        cmd="$cmd --cpu-model=${EP_CPU_MODEL}"
        if [ "$EP_SEQUENCER_MAX_OUTSTANDING" -gt 0 ] 2>/dev/null; then
            cmd="$cmd --sequencer-max-outstanding=${EP_SEQUENCER_MAX_OUTSTANDING}"
        fi
        echo "[launch] gem5 node=$nid (outdir=$node_od)"
        record_launch_command "$tc" gem5 "$nid" "" "$cmd"
        ( set +e; eval "$cmd" 2>"$gdir/stderr.log" >"$gdir/stdout.log"; status=$?; \
          printf '%s\n' "$status" >"$child_status_dir/gem5_node${nid}.exit"; exit "$status" ) &
        local pid=$!
        gem5_arr+=($pid)
        GEM5_PIDS="$GEM5_PIDS $pid"
    done

    # Wait for STEP5 Port enabled (NUM_SOCKETS of them per node)
    echo "[launch] waiting for NUM_NODES=$NUM_NODES gem5 to bind (sockets=$NUM_SOCKETS)..."
    for nid in $(seq 0 $((NUM_NODES-1))); do
        local glog_dir="$LOG_BASE/gem5_tc${tc}_node${nid}"
        local bound=0
        for tries in $(seq 1 300); do    # up to 300s wait (8-node init takes time)
            local bind_count
            bind_count=$(grep -h 'STEP5.*Port enabled' \
                "$glog_dir/stdout.log" "$glog_dir/stderr.log" 2>/dev/null | \
                wc -l)
            if [ "$bind_count" -ge "$NUM_SOCKETS" ]; then
                bound=1; break
            fi
            if ! kill -0 ${gem5_arr[$nid]} 2>/dev/null; then
                echo "[launch] gem5 node=$nid exited before binding!"
                _kill_infra
                return 1
            fi
            sleep 1
        done
        [ $bound -eq 1 ] && echo "[launch]   node=$nid bound" || {
            echo "[launch] node=$nid bind TIMEOUT"
            _kill_infra
            return 1
        }
    done

    echo "[launch] $n_ubio ubio (${NUM_NODES}x${NUM_SOCKETS}) + $NUM_NODES gem5 running"
    _start_memory_monitor "$tc"

    # 6b. Supervisor: opt-in long-run watchdog (EP_SUPERVISOR=1)
    if [ "${EP_SUPERVISOR:-0}" = "1" ]; then
        _supervisor_start "$tc" "$m5outdir" "$NUM_NODES"
    fi

    # 6. Wait for all gem5 processes to finish (or timeout)
    local waited=0
    local progress_size=-1
    local progress_waited=0
    local progress_watchdog="${PROGRESS_WATCHDOG_SEC:-0}"
    while true; do
        local any=0
        for pid in $GEM5_PIDS; do
            # A completed child remains a zombie until the wait below reaps it.
            # kill -0 succeeds for zombies, so do not mistake one for a running
            # gem5 process and leave UBIO/networksim running indefinitely.
            if kill -0 "$pid" 2>/dev/null; then
                local state
                state=$(ps -o stat= -p "$pid" 2>/dev/null || true)
                state=${state#${state%%[![:space:]]*}}
                case "$state" in
                    Z*) ;;
                    *) any=1 ;;
                esac
            fi
        done
        [ $any -eq 0 ] && break
        # TC9 is complete as soon as node0 proves the expected non-DSM page
        # fault. Peers intentionally remain blocked at their barrier, so
        # waiting for the generic testcase timeout only wastes runtime.
        if [ "$tc" -eq 9 ]; then
            local crash_log="$LOG_BASE/gem5_tc${tc}_node0/stderr.log"
            if grep -q "Page table fault when accessing virtual address 0xfffff8000000" \
                "$crash_log" 2>/dev/null; then
                echo "  TC${tc} PASSED (expected crash detected)"
                _supervisor_stop
                _kill_infra
                return 0
            fi
        fi
        sleep 1; waited=$((waited + 1))
        if [ "$progress_watchdog" -gt 0 ] 2>/dev/null; then
            local current_size=0
            # A node may finish its guest phase while peers are still doing
            # their work. Watch the aggregate output of every node, not node0
            # alone, so a valid asymmetric workload is not killed mid-run.
            for nid in $(seq 0 $((NUM_NODES-1))); do
                local progress_file="$m5outdir/node${nid}/simout_n${nid}"
                if [ -f "$progress_file" ]; then
                    current_size=$((current_size + $(stat -c %s "$progress_file")))
                fi
            done
            # Some workloads spend long intervals filling/spilling before a
            # guest printf. Treat bounded protocol-log growth as progress too;
            # without it a valid H64 backstore run is killed mid-transaction.
            for nid in $(seq 0 $((NUM_NODES-1))); do
                for sid in $(seq 0 $((NUM_SOCKETS-1))); do
                    local protocol_stream protocol_log
                    for protocol_stream in stdout.log stderr.log; do
                        protocol_log="$LOG_BASE/ubio_tc${tc}_n${nid}_s${sid}/$protocol_stream"
                        if [ -f "$protocol_log" ]; then
                            current_size=$((current_size + $(stat -c %s "$protocol_log")))
                        fi
                    done
                done
            done
            if [ "$current_size" -ne "$progress_size" ]; then
                progress_size="$current_size"
                progress_waited=0
            else
                progress_waited=$((progress_waited + 1))
                if [ "$progress_waited" -ge "$progress_watchdog" ]; then
                    echo "  TC${tc} PROGRESS STALL after ${progress_watchdog}s (no guest or protocol output)"
                    _supervisor_stop
                    _kill_infra
                    return 1
                fi
            fi
        fi
        if [ $waited -ge "$TC_TIMEOUT" ]; then
            # TC9 is a negative test: node0 is expected to crash on non-DSM
            # access (Aborted/SIGSEGV). If that crash evidence exists, the
            # test PASSED despite the timeout (other nodes may keep spinning).
            if [ "$tc" -eq 9 ]; then
                local crash_log="$LOG_BASE/gem5_tc${tc}_node0/stderr.log"
                if grep -q "Page table fault when accessing virtual address 0xfffff8000000" \
                    "$crash_log" 2>/dev/null; then
                    echo "  TC${tc} PASSED (expected crash detected)"
                    _supervisor_stop
                    _kill_infra
                    return 0
                fi
                echo "  TC${tc} TIMEOUT (no crash evidence found)"
            else
                echo "  TC${tc} TIMEOUT after ${TC_TIMEOUT}s"
            fi
            _supervisor_stop
            _kill_infra
            return 1
        fi
    done

    # Check exit codes
    local gem5_fail=0
    for pid in $GEM5_PIDS; do
        wait $pid 2>/dev/null || gem5_fail=1
    done

    # Let every UBIO wrapper record its real exit code before shutting down the
    # network simulator. networksim has no all-peer disconnect event, so after
    # UBIO exits the runner explicitly requests its graceful zero-status exit.
    local child_fail=0
    local shutdown_waited=0
    while [ "$shutdown_waited" -lt 15 ]; do
        local child_running=0
        for pid in $UBIO_PIDS; do
            if kill -0 "$pid" 2>/dev/null; then
                local child_state
                child_state=$(ps -o stat= -p "$pid" 2>/dev/null || true)
                child_state=${child_state#${child_state%%[![:space:]]*}}
                case "$child_state" in Z*) ;; *) child_running=1 ;; esac
            fi
        done
        [ "$child_running" -eq 0 ] && break
        sleep 1
        shutdown_waited=$((shutdown_waited + 1))
    done
    if [ "$shutdown_waited" -ge 15 ]; then
        echo "  TC${tc} CHILD SHUTDOWN TIMEOUT"
        child_fail=1
        for pid in $UBIO_PIDS ${NSIM_PID:-}; do kill "$pid" 2>/dev/null || true; done
        sleep 1
    elif [ -n "${NSIM_PID:-}" ]; then
        # Signal the recorded networksim child; its wrapper then reaps it and
        # writes networksim.exit with the simulator's real status.
        kill -TERM "$NSIM_CHILD_PID" 2>/dev/null || true

        shutdown_waited=0
        while [ "$shutdown_waited" -lt 15 ]; do
            if ! kill -0 "$NSIM_PID" 2>/dev/null; then
                break
            fi
            local nsim_state
            nsim_state=$(ps -o stat= -p "$NSIM_PID" 2>/dev/null || true)
            nsim_state=${nsim_state#${nsim_state%%[![:space:]]*}}
            case "$nsim_state" in Z*) break ;; esac
            sleep 1
            shutdown_waited=$((shutdown_waited + 1))
        done
        if [ "$shutdown_waited" -ge 15 ]; then
            echo "  TC${tc} NETWORKSIM SHUTDOWN TIMEOUT"
            child_fail=1
            _kill_pid_tree "$NSIM_PID"
        fi
    fi

    # Reap the wrappers so every managed process has a final status file.
    for pid in $UBIO_PIDS ${NSIM_PID:-}; do wait "$pid" 2>/dev/null || true; done

    local status_file status_code status_count=0
    for status_file in "$child_status_dir"/*.exit; do
        [ -f "$status_file" ] || continue
        status_count=$((status_count + 1))
        status_code=$(tr -d '[:space:]' <"$status_file")
        if [ "$status_code" != "0" ]; then
            echo "  TC${tc} CHILD FAILED: $(basename "$status_file") exit=$status_code"
            child_fail=1
        fi
    done
    local expected_status_count=$((NUM_NODES * NUM_SOCKETS + NUM_NODES + 1))
    if [ "$status_count" -ne "$expected_status_count" ]; then
        echo "  TC${tc} CHILD FAILED: expected ${expected_status_count} exit files, found ${status_count}"
        child_fail=1
    fi

    # All child wrappers are reaped. Stop only auxiliary monitoring here.
    _supervisor_stop
    if [ -n "${MEMORY_MONITOR_PID:-}" ]; then
        kill "$MEMORY_MONITOR_PID" 2>/dev/null || true
        MEMORY_MONITOR_PID=""
    fi
    sleep 0.2

    if [ $gem5_fail -ne 0 ] || [ $child_fail -ne 0 ]; then
        # TC9 is a negative test: node0 must reject the unmapped non-DSM
        # access. The crash can happen before the timeout loop observes it.
        if [ "$tc" -eq 9 ]; then
            local crash_log="$LOG_BASE/gem5_tc${tc}_node0/stderr.log"
            if grep -q "Page table fault when accessing virtual address 0xfffff8000000" \
                "$crash_log" 2>/dev/null; then
                echo "  TC${tc} PASSED (expected crash detected)"
                return 0
            fi
        fi
        echo "  TC${tc} CRASHED (a managed child exited non-zero)"
        return 1
    fi

    # 7. Verify via independent verify.py
    local simouts=()
    for nid in $(seq 0 $((NUM_NODES-1))); do
        local simout="$m5outdir/node${nid}/simout_n${nid}"
        simouts+=("$simout")
        if [ -f "$simout" ]; then
            cp "$simout" "$LOG_BASE/simout_tc${tc}_node${nid}.log" 2>/dev/null || true
        fi
    done
    local faultlogs=()
    for nid in $(seq 0 $((NUM_NODES-1))); do
        for sid in $(seq 0 $((NUM_SOCKETS-1))); do
            faultlogs+=("$LOG_BASE/ubio_tc${tc}_n${nid}_s${sid}/stdout.log")
        done
        faultlogs+=("$LOG_BASE/gem5_tc${tc}_node${nid}/stderr.log")
    done
    faultlogs+=("$LOG_BASE/launch_manifest.txt")
    # Strict UBFAULT events are consumed directly from the raw UBIO logs.
    # Keep a separate auxiliary input only for TC111's gem5 silent-upgrade
    # markers, which do not originate in an UBIO log.
    if [ "$tc" -eq 111 ]; then
        local fault_evidence="$LOG_BASE/fault_evidence_tc${tc}.log"
        : >"$fault_evidence"
        for nid in $(seq 0 $((NUM_NODES-1))); do
            for marker_log in \
                "$LOG_BASE/gem5_tc${tc}_node${nid}/stdout.log" \
                "$LOG_BASE/gem5_tc${tc}_node${nid}/gem5_debug.log"; do
                if [ -f "$marker_log" ]; then
                    while IFS= read -r marker_line; do
                        case "$marker_line" in
                            *'kind=upgrade_silent'*|*'SILENT-WRITE-HIT'*|*'silent upgrade'*'zero cross-node'*|*'silent upgrade'*'0 cross-node'*)
                                printf '%s\n' "$marker_line" >>"$fault_evidence"
                                ;;
                        esac
                    done <"$marker_log"
                fi
            done
        done
        faultlogs+=("$fault_evidence")
    fi
    local vlog="$LOG_BASE/verify_tc${tc}.log"
    local effective_fault_rules
    effective_fault_rules="$(fault_rules_for_tc "$tc")"
    local verify_cmd=(python3 "$ROOT_DIR/tests/e2e/verify.py" "--tc=$tc"
                      --simout "${simouts[@]}" --fault-log "${faultlogs[@]}")
    if [ -n "$effective_fault_rules" ]; then
        verify_cmd+=(--fault-rules "$effective_fault_rules")
    fi
    "${verify_cmd[@]}" 2>&1 | tee "$vlog"
    # Last sentinel line decides
    if tail -n1 "$vlog" 2>/dev/null | grep -q ">>> TC${tc} PASSED <<<"; then
        if ! python3 "$ROOT_DIR/scripts/verify_peer_exit_logs.py" \
            "$LOG_BASE" --tc "$tc" --num-nodes "$NUM_NODES" \
            --num-sockets "$NUM_SOCKETS"; then
            echo "  TC${tc} FAILED (PeerExit contract)"
            return 1
        fi
        # Persist request issue-to-first-response chains for cross-run latency
        # evaluation.  TRACE-PERF is emitted by gem5, UBIO, and networksim.
        python3 "$ROOT_DIR/scripts/trace2chain.py" "$LOG_BASE" \
            >"$LOG_BASE/trace_chains_tc${tc}.json" 2>/dev/null || true
        echo "  TC${tc} PASSED"
        return 0
    else
        echo "  TC${tc} FAILED"
        return 1
    fi
}

# ── Main ─────────────────────────────────────────────────────────────
[ -x "$GEM5_BIN" ] || { echo "FATAL: $GEM5_BIN not built"; exit 2; }
[ -x "$UBIO_BIN" ] || { echo "FATAL: $UBIO_BIN not built"; exit 2; }
[ -x "$NSIM_BIN" ] || { echo "FATAL: $NSIM_BIN not built"; exit 2; }

echo "=== Multi-Process E2E Runner (decoupled, topo=$TOPO_KIND) ==="
echo "Config:  $JSON"
echo "Log base: $LOG_BASE"
echo "Sockets/node: $NUM_SOCKETS  (NMOD=$NMOD)"
echo "Workload: $WORKLOAD  (compiled per-TC; path is constant)"

# These workloads embed a fixed node/socket count and barrier mask. Reject a
# mismatch before compiling or starting any managed process.
required_topology_for_tc() {
    case "$1" in
        135|136|137|138|139|140|141)          printf '%s\n' 1s ;;
        32|33|34|35|39|81)                 printf '%s\n' 2s ;;
        82|90|91|92|93|94|133)             printf '%s\n' 8n1s ;;
        95|96|97|98|99|100|101|134)        printf '%s\n' 8n2s ;;
        160)                                printf '%s\n' 16n1s ;;
        210|211|212|213|214|215|216|217|218|219|220|221|222|223|224|225|226|227) printf '%s\n' 2n1s ;;
    esac
}

for tc in "$@"; do
    required_topology="$(required_topology_for_tc "$tc")"
    if [ -n "$required_topology" ] && [ "$TOPO_KIND" != "$required_topology" ]; then
        echo "FATAL: TC$tc requires --$required_topology topology. Re-run with --$required_topology." >&2
        exit 2
    fi
done

PASS=0; FAIL=0
for tc in "$@"; do
    if UBIO_PIDS="" run_tc "$tc"; then PASS=$((PASS+1)); else FAIL=$((FAIL+1)); fi
    # cleanup any stragglers between TCs
    for pid in ${UBIO_PIDS:-} ${NSIM_PID:-}; do kill $pid 2>/dev/null || true; done
done

echo ""
echo "=== Results: $PASS pass, $FAIL fail ==="
echo "Logs: $LOG_BASE"

