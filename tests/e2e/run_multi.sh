#!/bin/bash
# Multi-Process E2E Runner (per-node gem5 split) — decoupled edition
#
# This launcher reads a fixed JSON topology config (configs/topo_1s.json or
# configs/topo_2s.json), generates the networksim topo.json, compiles the
# workload into a run-specific path, starts all module processes per the JSON,
# waits for gem5 to finish, then invokes the independent verifier
# tests/e2e/verify.py. Set E2E_RUN_ID to run independent TCs concurrently.
#
# Usage:
#   bash tests/e2e/run_multi.sh [--1s|--2s|--16n1s] <tc> ... [<tc> ...]
#
# Default is --1s. Dual-socket TCs (32-35,39) require --2s; if you pass a
# dual-socket TC under --1s the script will auto-error.
#
# ── Long-run supervised invocation ────────────────────────────────────
# The runner does NOT background itself. For long-running TCs (132-134):
#   nohup env EP_SUPERVISOR=1 bash tests/e2e/run_multi.sh --8n1s 132 \
#     > /tmp/run_132.log 2>&1 &
# Opt-in supervisor (EP_SUPERVISOR=1) adds watchdog monitoring with:
#   - PID manifest in LOG_BASE
#   - Periodic liveness / progress / log-size / disk-free checks
#   - Clean per-TC kill on fault; never uses pkill
# Supervisor env vars (all default-off):
#   EP_SUPERVISOR=1              enable (default unset=off)
#   EP_SUPERVISOR_INTERVAL=30    check interval seconds (default 30)
#   EP_SUPERVISOR_LOG_CEIL_GB=20 max log dir GiB ceiling (default 20)
#   EP_SUPERVISOR_DISK_FREE_GB=50 min disk free GiB (default 50)
#   EP_SUPERVISOR_PROGRESS_STALL_SEC=600 stop after no simout growth
#
# TRACE-PERF is bounded by default to prevent capacity tests from producing
# one record per protocol hop. The first 500 events per process are retained.
#   EP_TRACE_PERF=sample|full|off  (default sample)
#   EP_TRACE_PERF_FIRST_N=500 EP_TRACE_PERF_MAX=2000 EP_TRACE_PERF_EVERY=0
# Full mode preserves the historical every-event trace; add MAX explicitly
# when a diagnostic run must also have a finite output budget.
# IPC is bounded by default so a stalled peer exerts backpressure rather than
# consuming host memory. Override only for controlled transport experiments.
#   EP_PORT_HWM=8192 EP_NSIM_MAX_PENDING=65536
#
# topology (*) is fixed in the JSON files; the networksim crossbar mesh is
# regenerated by scripts/gen_topo.py to match (NMOD depends only on topology).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"
GEM5_BIN="$ROOT_DIR/gem5/build/ARM/gem5.opt"
if [ ! -x "$GEM5_BIN" ] && [ -x "$ROOT_DIR/gem5/gem5/build/ARM/gem5.opt" ]; then
    GEM5_BIN="$ROOT_DIR/gem5/gem5/build/ARM/gem5.opt"
fi
UBIO_BIN="$ROOT_DIR/build/bin/ubio"
NSIM_BIN="$ROOT_DIR/build/bin/networksim"
TEST_E2E="$ROOT_DIR/tests/e2e/test_e2e.py"
RUN_ID="${E2E_RUN_ID:-$(date +%Y%m%d_%H%M%S)_$$}"
RUN_DIR="$ROOT_DIR/build/runs/$RUN_ID"
WORKLOAD="$RUN_DIR/workload.elf"
TOPO_JSON="$RUN_DIR/topo.json"
IPC_DIR="${E2E_IPC_DIR:-$ROOT_DIR/gem5/shared_ipc/$RUN_ID}"
TIMEOUT_SEC="${TIMEOUT_SEC:-600}"

# ── Supervisor (opt-in long-run watchdog) conf ─────────────────────
EP_SUPERVISOR="${EP_SUPERVISOR:-0}"
EP_SUPERVISOR_INTERVAL="${EP_SUPERVISOR_INTERVAL:-30}"
EP_SUPERVISOR_LOG_CEIL_GB="${EP_SUPERVISOR_LOG_CEIL_GB:-20}"
EP_SUPERVISOR_DISK_FREE_GB="${EP_SUPERVISOR_DISK_FREE_GB:-50}"
EP_SUPERVISOR_PROGRESS_STALL_SEC="${EP_SUPERVISOR_PROGRESS_STALL_SEC:-600}"

# C5: PDES sync interval (ps).  Lower values improve time-resolution but
# increase IPC overhead.  Target: 2.5ns (2500 ps) per solve_latency_params.py --x-ns 2.5.
export EP_SYNC_INTERVAL_PS="${EP_SYNC_INTERVAL_PS:-2500}"
export EP_LINK_LATENCY_PS="${EP_LINK_LATENCY_PS:-2500}"

# Phase 0: Metadata DRAM capacity — single source of truth for gem5 and ubio.
# gem5 gets --ubcc_metadata_size; ubio gets --metadata-dram-bytes.
# Both default to 128 MiB (134217728 bytes).  Override this variable to
# use a different capacity (e.g. 16 MiB legacy: UBCC_METADATA_SIZE=16777216).
export UBCC_METADATA_SIZE="${UBCC_METADATA_SIZE:-134217728}"
export EP_TRACE_PERF="${EP_TRACE_PERF:-sample}"
export EP_TRACE_PERF_FIRST_N="${EP_TRACE_PERF_FIRST_N:-500}"
export EP_TRACE_PERF_MAX="${EP_TRACE_PERF_MAX:-2000}"
export EP_TRACE_PERF_EVERY="${EP_TRACE_PERF_EVERY:-0}"
export EP_PORT_HWM="${EP_PORT_HWM:-8192}"
export EP_NSIM_MAX_PENDING="${EP_NSIM_MAX_PENDING:-65536}"
export EP_CPU_MODEL="${EP_CPU_MODEL:-timing}"
export EP_SEQUENCER_MAX_OUTSTANDING="${EP_SEQUENCER_MAX_OUTSTANDING:-0}"
export EP_L3_SIZE="${EP_L3_SIZE:-256kB}"
export EP_L3_ASSOC="${EP_L3_ASSOC:-16}"
export L3_PRESSURE_LEVEL="${L3_PRESSURE_LEVEL:-0}"
export L3_PRESSURE_TARGET_LINES="${L3_PRESSURE_TARGET_LINES:-}"
export METRIC3_L3_SEED="${METRIC3_L3_SEED:-0}"
export METRIC3_L3_EXPERIMENT_MODE="${METRIC3_L3_EXPERIMENT_MODE:-l3-only}"
export L3_DIRECTORY_PRESSURE_LINES="${L3_DIRECTORY_PRESSURE_LINES:-0}"
export EP_TRACK_L3_OCCUPANCY="${EP_TRACK_L3_OCCUPANCY:-0}"
case "$L3_PRESSURE_LEVEL" in 0|100|150) ;; *) echo "FATAL: L3_PRESSURE_LEVEL must be 0, 100, or 150" >&2; exit 2 ;; esac
if [ -n "$L3_PRESSURE_TARGET_LINES" ] && \
   ! [[ "$L3_PRESSURE_TARGET_LINES" =~ ^[0-9]+$ ]]; then
    echo "FATAL: L3_PRESSURE_TARGET_LINES must be empty or a non-negative integer" >&2
    exit 2
fi
if [ -n "$L3_PRESSURE_TARGET_LINES" ] && [ "$L3_PRESSURE_LEVEL" != 0 ]; then
    echo "FATAL: absolute L3 pressure requires L3_PRESSURE_LEVEL=0" >&2
    exit 2
fi
case "$METRIC3_L3_EXPERIMENT_MODE" in
    l3-only)
        [ "$L3_DIRECTORY_PRESSURE_LINES" -eq 0 ] || {
            echo "FATAL: l3-only requires L3_DIRECTORY_PRESSURE_LINES=0" >&2
            exit 2
        }
        ;;
    l3-offload)
        [ "$L3_DIRECTORY_PRESSURE_LINES" -gt 57344 ] || {
            echo "FATAL: l3-offload requires more than 57344 directory pressure lines" >&2
            exit 2
        }
        ;;
    *) echo "FATAL: METRIC3_L3_EXPERIMENT_MODE must be l3-only or l3-offload" >&2; exit 2 ;;
esac
if ! [[ "$EP_L3_ASSOC" =~ ^[1-9][0-9]*$ ]]; then
    echo "FATAL: EP_L3_ASSOC must be a positive integer" >&2
    exit 2
fi
case "$EP_L3_SIZE" in
    *KiB) EP_L3_VALUE=${EP_L3_SIZE%KiB}; EP_L3_MULTIPLIER=1024 ;;
    *kB)  EP_L3_VALUE=${EP_L3_SIZE%kB};  EP_L3_MULTIPLIER=1024 ;;
    *MiB) EP_L3_VALUE=${EP_L3_SIZE%MiB}; EP_L3_MULTIPLIER=$((1024 * 1024)) ;;
    *MB)  EP_L3_VALUE=${EP_L3_SIZE%MB};  EP_L3_MULTIPLIER=$((1024 * 1024)) ;;
    *B)   EP_L3_VALUE=${EP_L3_SIZE%B};   EP_L3_MULTIPLIER=1 ;;
    *) echo "FATAL: EP_L3_SIZE must use B, kB/KiB, or MB/MiB" >&2; exit 2 ;;
esac
if ! [[ "$EP_L3_VALUE" =~ ^[1-9][0-9]*$ ]]; then
    echo "FATAL: EP_L3_SIZE must have a positive integer magnitude" >&2
    exit 2
fi
EP_L3_BYTES=$((EP_L3_VALUE * EP_L3_MULTIPLIER))
if ! [[ "$EP_L3_BYTES" =~ ^[1-9][0-9]*$ ]] || \
   [ $((EP_L3_BYTES % (64 * EP_L3_ASSOC))) -ne 0 ]; then
    echo "FATAL: EP_L3_SIZE must be a positive multiple of 64*EP_L3_ASSOC" >&2
    exit 2
fi
export EP_L3_CACHE_LINES=$((EP_L3_BYTES / 64))
export EP_L3_SETS=$((EP_L3_CACHE_LINES / EP_L3_ASSOC))
if [ $((EP_L3_SETS & (EP_L3_SETS - 1))) -ne 0 ]; then
    echo "FATAL: EP_L3_SIZE/(64*EP_L3_ASSOC) must be a power of two" >&2
    exit 2
fi
if [ -n "$L3_PRESSURE_TARGET_LINES" ]; then
    EP_L3_PRESSURE_TARGET_LINES="$L3_PRESSURE_TARGET_LINES"
else
    EP_L3_PRESSURE_TARGET_LINES=$((EP_L3_CACHE_LINES * L3_PRESSURE_LEVEL / 100))
fi
export EP_L3_PRESSURE_TARGET_LINES
if [ "$EP_L3_PRESSURE_TARGET_LINES" -gt 0 ] && \
   [ $((0x2000000 + 5 * 0x100000 + \
          EP_L3_PRESSURE_TARGET_LINES * 64)) \
      -ge $((0x8000000)) ]; then
    echo "FATAL: L3 pressure region exceeds the 128 MiB DSM segment" >&2
    exit 2
fi
if [ "$L3_DIRECTORY_PRESSURE_LINES" -gt 0 ] && \
   [ $((0x4000000 + L3_DIRECTORY_PRESSURE_LINES * 64)) -ge $((0x7800000)) ]; then
    echo "FATAL: directory pressure region exceeds its reserved DSM range" >&2
    exit 2
fi
# PeerExit tolerates bounded transient loss/delay by retrying Notify while the
# receiver remains in this bounded quiesce responder window. These defaults
# fit comfortably inside the runner's 15-second shutdown grace period.
export UBIO_PEER_EXIT_RETRY_MS="${UBIO_PEER_EXIT_RETRY_MS:-100}"
export UBIO_PEER_EXIT_QUIESCE_MS="${UBIO_PEER_EXIT_QUIESCE_MS:-2000}"
export UBIO_PEER_EXIT_DELIVERY_BUDGET_MS="${UBIO_PEER_EXIT_DELIVERY_BUDGET_MS:-1000}"
export EP_HA_PROFILE="${EP_HA_PROFILE:-ubcc}"
export OURCC_CLEAR_PROFILE="${OURCC_CLEAR_PROFILE:-ack}"
HA_EXACT_BYTES="${HA_EXACT_BYTES:-}"
export HA_MAX_ACTIVE="${HA_MAX_ACTIVE:-256}"
export HA_MAX_QUEUE="${HA_MAX_QUEUE:-8}"

case "$OURCC_CLEAR_PROFILE" in
    ack|lossless-oneway) ;;
    *) echo "FATAL: OURCC_CLEAR_PROFILE must be ack or lossless-oneway" >&2; exit 2 ;;
esac
if [ "$OURCC_CLEAR_PROFILE" = "lossless-oneway" ] && [ "$EP_HA_PROFILE" != "ubcc" ]; then
    echo "FATAL: lossless-oneway Clear is only valid with EP_HA_PROFILE=ubcc" >&2
    exit 2
fi

# ── Config selection ────────────────────────────────────────────────
TOPO_KIND="1s"
GENERATED_TOPO_NODES=""
GENERATED_TOPO_SOCKETS=""
case "${1:-}" in
    --1s)          TOPO_KIND="1s"; shift ;;
    --3n1s)        TOPO_KIND="3n1s"; GENERATED_TOPO_NODES=3; GENERATED_TOPO_SOCKETS=1; shift ;;
    --3n2s)        TOPO_KIND="3n2s"; GENERATED_TOPO_NODES=3; GENERATED_TOPO_SOCKETS=2; shift ;;
    --4n1s)        TOPO_KIND="4n1s"; GENERATED_TOPO_NODES=4; GENERATED_TOPO_SOCKETS=1; shift ;;
    --1s-tinydir)  TOPO_KIND="1s_tinydir"; shift ;;
    --2s)          TOPO_KIND="2s"; shift ;;
    --2n2s)        TOPO_KIND="2n2s"; GENERATED_TOPO_NODES=2; GENERATED_TOPO_SOCKETS=2; shift ;;
    --4n2s)        TOPO_KIND="4n2s"; GENERATED_TOPO_NODES=4; GENERATED_TOPO_SOCKETS=2; shift ;;
    --8n1s)        TOPO_KIND="8n1s"; shift ;;
    --8n2s)        TOPO_KIND="8n2s"; shift ;;
    --2n1s)        TOPO_KIND="2n1s"; shift ;;
    --16n1s)       TOPO_KIND="16n1s"; shift ;;
esac

# Optional experiment contract flags. They are deliberately parsed by the
# common runner so the audited command line and the effective process settings
# cannot drift apart in wrapper scripts.
E2E_FORMAL=0
E2E_AUDIT_PROFILE="${EP_PERF_PROFILE:-}"
while [ $# -gt 0 ]; do
    case "$1" in
        --formal)
            E2E_FORMAL=1
            shift
            ;;
        --profile)
            [ $# -ge 2 ] || { echo "FATAL: --profile requires naive, spill-noopt, or optimized" >&2; exit 2; }
            E2E_AUDIT_PROFILE="$2"
            shift 2
            ;;
        --profile=*)
            E2E_AUDIT_PROFILE="${1#--profile=}"
            shift
            ;;
        --) shift; break ;;
        *) break ;;
    esac
done
if [ -n "$E2E_AUDIT_PROFILE" ]; then
    case "$E2E_AUDIT_PROFILE" in
        naive)       export EP_PERF_PROFILE=naive;       export UBCC_POLICY=naive ;;
        spill-noopt) export EP_PERF_PROFILE=spill-noopt; export UBCC_POLICY=spill ;;
        optimized)   export EP_PERF_PROFILE=optimized;   export UBCC_POLICY=spill ;;
        *) echo "FATAL: --profile must be naive, spill-noopt, or optimized" >&2; exit 2 ;;
    esac
fi
if [ "$E2E_FORMAL" = 1 ]; then
    export EP_CPU_MODEL=o3
    export EP_SEQUENCER_MAX_OUTSTANDING=16
    export EP_SYNC_INTERVAL_PS=2500
    export EP_LINK_LATENCY_PS=2500
    export EP_PORT_HWM=8192
    export EP_NSIM_MAX_PENDING=65536
fi
if [ -n "$GENERATED_TOPO_NODES" ]; then
    JSON="$RUN_DIR/process_topology.json"
    mkdir -p "$RUN_DIR"
    python3 "$ROOT_DIR/scripts/gen_process_topology.py" \
        --nodes "$GENERATED_TOPO_NODES" --sockets "$GENERATED_TOPO_SOCKETS" \
        --out "$JSON"
else
    JSON="$ROOT_DIR/configs/topo_${TOPO_KIND}.json"
fi
[ -f "$JSON" ] || { echo "FATAL: config $JSON not found" >&2; exit 2; }

# ── Determine sockets + nmod from JSON ───────────────────────────────
read NUM_NODES NUM_SOCKETS < <(python3 -c "
import json
c=json.load(open('$JSON'))
print(c['num_nodes'], c['num_sockets'])
")
NMOD=$((NUM_NODES * NUM_SOCKETS))
if [ -z "$HA_EXACT_BYTES" ]; then
    # 512 KiB exact bitmap budget, one participant bit per node/socket plane.
    HA_EXACT_BYTES=$(( (512 * 1024 * 8 / NMOD) * 64 ))
fi
export HA_EXACT_BYTES

# ── Per-TC fault-injection rules (ubio --fault-rules=...) ────────────
fault_rules_for_tc() {
    if [ -n "${E2E_FAULT_RULES_OVERRIDE:-}" ]; then
        printf '%s\n' "$E2E_FAULT_RULES_OVERRIDE"
        return
    fi
    case "$1" in
        47) echo "tc47_drop_clear:ClearReq:1:0:0:drop::1" ;;
        48) echo "tc48_dup_inv_ack:InvalidateAck:2:0:0:dup::1" ;;
        49) echo "tc49_reorder_inv_ack:InvalidateAck:1:0:0:reorder:100000:1" ;;
        110) echo "tc110_drop_clear:ClearReq:1:1:0:drop::1" ;;
        111) echo "tc111_silent_upgrade_drop:UpgradeReq:1:1:0:drop::1" ;;
        117) echo "tc117_reorder_clear:ClearReq:0:1:0:reorder:100000:1" ;;
        118) echo "tc118_drop:ClearReq:0:1:0x10018011800:drop::1;tc118_delay:ClearReq:0:1:0x10018011900:delay:100000:1" ;;
        119) echo "tc119_drop:ClearReq:0:1:0x10018011900:drop::1;tc119_dup:ClearReq:0:1:0x10018011940:dup::1;tc119_delay:ClearReq:0:1:0x10018011980:delay:100000:1" ;;
        148)
            local rules="" action idx global_idx pa delay
            global_idx=0
            for action in drop dup delay reorder; do
                for idx in $(seq 0 7); do
                    pa=$(printf '0x%x' $((0x10018014800 + global_idx * 64)))
                    delay=""
                    case "$action" in
                        delay) delay=20000 ;;
                        reorder) delay=100000 ;;
                    esac
                    [ -n "$rules" ] && rules="$rules;"
                    rules="${rules}tc148_${action}_${idx}:ClearReq:0:1:${pa}:${action}:${delay}:1"
                    global_idx=$((global_idx + 1))
                done
            done
            echo "$rules"
            ;;
        149)
            local rules="" idx pa
            for idx in $(seq 0 7); do
                pa=$(printf '0x%x' $((0x10018014900 + idx * 64)))
                [ -n "$rules" ] && rules="$rules;"
                rules="${rules}tc149_upgrade_drop_${idx}:UpgradeReq:0:1:${pa}:drop::1"
            done
            echo "$rules"
            ;;
        150|151|152)
            local rules="" idx node pa action delay prefix
            case "$1" in
                150) action=dup; delay=""; prefix=invack_dup ;;
                151) action=delay; delay=20000; prefix=invack_delay ;;
                152) action=reorder; delay=100000; prefix=invack_reorder ;;
            esac
            for node in 1 2; do
                for idx in $(seq 0 7); do
                    pa=$(printf '0x%x' $((0x10018014900 + idx * 64)))
                    [ -n "$rules" ] && rules="$rules;"
                    rules="${rules}tc${1}_${prefix}_n${node}_${idx}:InvalidateAck:${node}:1:${pa}:${action}:${delay}:1"
                done
            done
            echo "$rules"
            ;;
        153|154|155|156)
            local rules="" idx pa action delay prefix
            case "$1" in
                153) action=dup; delay=""; prefix=recall_dup ;;
                154) action=delay; delay=20000; prefix=recall_delay ;;
                155) action=reorder; delay=100000; prefix=recall_reorder ;;
                156) action=drop; delay=""; prefix=recall_drop ;;
            esac
            for idx in $(seq 0 15); do
                pa=$(printf '0x%x' $((0x10018015300 + idx * 64)))
                [ -n "$rules" ] && rules="$rules;"
                rules="${rules}tc${1}_${prefix}_${idx}:RecallResp:0:1:${pa}:${action}:${delay}:1"
            done
            echo "$rules"
            ;;
        157)
            local rules="" idx node pa
            for node in 1 2; do
                for idx in $(seq 0 7); do
                    pa=$(printf '0x%x' $((0x10018014900 + idx * 64)))
                    [ -n "$rules" ] && rules="$rules;"
                    rules="${rules}tc157_invack_drop_n${node}_${idx}:InvalidateAck:${node}:1:${pa}:drop::1"
                done
            done
            echo "$rules"
            ;;
        158|159)
            local rules="" idx pa type prefix src dst
            if [ "$1" = "158" ]; then
                type=UpgradeResp; prefix=upgraderesp_drop; src=1; dst=0
            else
                type=UpgradeAckNotify; prefix=upgradeack_drop; src=1; dst=0
            fi
            for idx in $(seq 0 7); do
                pa=$(printf '0x%x' $((0x10018014900 + idx * 64)))
                [ -n "$rules" ] && rules="$rules;"
                rules="${rules}tc${1}_${prefix}_${idx}:${type}:${src}:${dst}:${pa}:drop::1"
            done
            echo "$rules"
            ;;
        *)  echo "" ;;
    esac
}

# ── Per-TC extra ubio args (ResidentDir params, etc.) ──────────────
ubio_extra_args_for_tc() {
    case "$1" in
        116) echo "--bloom-bytes=512 --sram-bytes=6144 --ways=2 ${UBCC_POLICY:+--dir-overflow-policy=$UBCC_POLICY} ${UBCC_OPTS:-}" ;;
        120)
            case "${EP_PERF_PROFILE:-optimized}" in
                naive|baseline) echo "--bloom-bytes=512 --sram-bytes=5000 --ways=2 --set-bits=2 --dir-overflow-policy=naive --batch-rs=0 ${UBCC_OPTS:-}" ;;
                spill-noopt) echo "--bloom-bytes=512 --sram-bytes=5000 --ways=2 --set-bits=2 --dir-overflow-policy=spill --batch-rs=0 ${UBCC_OPTS:-}" ;;
                optimized|*) echo "--bloom-bytes=512 --sram-bytes=5000 --ways=2 --set-bits=2 --dir-overflow-policy=${UBCC_POLICY:-spill} --batch-rs=1 ${UBCC_OPTS:-}" ;;
            esac
            ;;
        121)
            case "${EP_PERF_PROFILE:-optimized}" in
                naive|baseline) echo "--bloom-bytes=512 --sram-bytes=5000 --ways=2 --set-bits=2 --dir-overflow-policy=naive --batch-rs=0 ${UBCC_OPTS:-}" ;;
                spill-noopt) echo "--bloom-bytes=512 --sram-bytes=5000 --ways=2 --set-bits=2 --dir-overflow-policy=spill --batch-rs=0 ${UBCC_OPTS:-}" ;;
                optimized|*) echo "--bloom-bytes=512 --sram-bytes=5000 --ways=2 --set-bits=2 --dir-overflow-policy=${UBCC_POLICY:-spill} --batch-rs=1 ${UBCC_OPTS:-}" ;;
            esac
            ;;
        122|123)
            case "${EP_PERF_PROFILE:-optimized}" in
                naive|baseline) echo "--bloom-bytes=512 --sram-bytes=6144 --ways=2 --dir-overflow-policy=naive --batch-rs=0 ${UBCC_OPTS:-}" ;;
                spill-noopt) echo "--bloom-bytes=512 --sram-bytes=6144 --ways=2 --dir-overflow-policy=spill --batch-rs=0 ${UBCC_OPTS:-}" ;;
                optimized|*) echo "--bloom-bytes=512 --sram-bytes=6144 --ways=2 --dir-overflow-policy=${UBCC_POLICY:-spill} --batch-rs=1 ${UBCC_OPTS:-}" ;;
            esac
            ;;
        124)
            case "${EP_PERF_PROFILE:-optimized}" in
                naive|baseline|spill-noopt) echo "--batch-rs=0 ${UBCC_OPTS:-}" ;;
                optimized|*) echo "--batch-rs=1 ${UBCC_OPTS:-}" ;;
            esac
            ;;
        125|126|127|128|129)
            case "${EP_PERF_PROFILE:-spill-noopt}" in
                optimized) echo "--bloom-bytes=512 --sram-bytes=6144 --ways=1 --dir-overflow-policy=spill --batch-rs=1 ${UBCC_OPTS:-}" ;;
                *)         echo "--bloom-bytes=512 --sram-bytes=6144 --ways=1 --dir-overflow-policy=spill --batch-rs=0 ${UBCC_OPTS:-}" ;;
            esac
            ;;
        130|135|136|137|138|139|141)
            case "${EP_PERF_PROFILE:-spill-noopt}" in
                naive|baseline) echo "--bloom-bytes=${UBCC_BLOOM_BYTES:-512} --sram-bytes=5000 --ways=2 --set-bits=2 --dir-overflow-policy=naive --batch-rs=0 ${UBCC_OPTS:-}" ;;
                optimized) echo "--bloom-bytes=${UBCC_BLOOM_BYTES:-512} --sram-bytes=5000 --ways=2 --set-bits=2 --dir-overflow-policy=spill --batch-rs=1 ${UBCC_OPTS:-}" ;;
                *) echo "--bloom-bytes=${UBCC_BLOOM_BYTES:-512} --sram-bytes=5000 --ways=2 --set-bits=2 --dir-overflow-policy=spill --batch-rs=0 ${UBCC_OPTS:-}" ;;
            esac
            ;;
        142|143|144|145|146|147)
            if [ "${PORTABLE_512K_DIR:-0}" = "1" ]; then
                local portable_policy=spill portable_bloom=61440 portable_batch=0
                case "${EP_PERF_PROFILE:-spill-noopt}" in
                    naive|baseline) portable_policy=naive; portable_bloom=0 ;;
                    optimized) portable_batch=1 ;;
                esac
                echo "--bloom-bytes=$portable_bloom --sram-bytes=524288 --ways=0 --set-bits=0 --dir-overflow-policy=$portable_policy --batch-rs=$portable_batch ${UBCC_OPTS:-}"
                return
            fi
            # Legacy tiny-directory stress profile.
            case "${EP_PERF_PROFILE:-spill-noopt}" in
                naive|baseline) echo "--bloom-bytes=128 --sram-bytes=4352 --ways=1 --set-bits=0 --dir-overflow-policy=naive --batch-rs=0 ${UBCC_OPTS:-}" ;;
                optimized) echo "--bloom-bytes=128 --sram-bytes=4352 --ways=1 --set-bits=0 --dir-overflow-policy=spill --batch-rs=1 ${UBCC_OPTS:-}" ;;
                *) echo "--bloom-bytes=128 --sram-bytes=4352 --ways=1 --set-bits=0 --dir-overflow-policy=spill --batch-rs=0 ${UBCC_OPTS:-}" ;;
            esac
            ;;
        140)
            case "${EP_PERF_PROFILE:-spill-noopt}" in
                optimized) echo "--batch-rs=1 ${UBCC_OPTS:-}" ;;
                *) echo "--batch-rs=0 ${UBCC_OPTS:-}" ;;
            esac
            ;;
        131|132|133|134)
            # ── Phase A1: Unambiguous policy selection ──
            # TC131-134 overflow policy is controlled by UBCC_POLICY env var
            # (not EP_PERF_PROFILE). Valid values: spill (default), naive.
            # Use UBCC_POLICY=naive to select naive-evict; spill otherwise.
            local policy="${UBCC_POLICY:-spill}"
            local bloom_bytes=61440
            if [ "$policy" = "naive" ]; then
                bloom_bytes=0
            fi
            # Emit manifest marker for verifier consumption (stdout + log)
            printf "[RUNNER-MANIFEST] TC%d policy=%s bloom_bytes=%d sram_bytes=524288\n" \
                "$1" "$policy" "$bloom_bytes" >&2
            echo "--bloom-bytes=$bloom_bytes --sram-bytes=524288 --ways=0 --set-bits=0 --dir-overflow-policy=$policy --batch-rs=0 ${UBCC_OPTS:-}"
            ;;
        200)
            # Phase A3: tiny naive ResidentDir for capacity-pressure recall test
            echo "--bloom-bytes=0 --sram-bytes=64 --ways=1 --set-bits=0 --dir-overflow-policy=naive --batch-rs=0 ${UBCC_OPTS:-}"
            ;;
        201)
            # Phase A5: tiny spill ResidentDir + backstore for durability test.
            # sram-bytes must exceed bloom+index (128+4096=4224) to avoid underflow.
            echo "--bloom-bytes=128 --sram-bytes=4352 --ways=1 --set-bits=3 --dir-overflow-policy=spill --batch-rs=0 ${UBCC_OPTS:-}"
            ;;
        202)
            # Phase C1: spill push-grant authoritative home-data test
            echo "--bloom-bytes=128 --sram-bytes=4352 --ways=1 --set-bits=0 --dir-overflow-policy=spill --batch-rs=0 ${UBCC_OPTS:-}"
            ;;
        203)
            # Phase 5: H64 spill/onload regression. Hash collision and
            # tombstone semantics are tested directly by the focused Host test.
            echo "--bloom-bytes=128 --sram-bytes=4352 --ways=1 --set-bits=0 --dir-overflow-policy=spill --batch-rs=0 ${UBCC_OPTS:-}"
            ;;
        160)
            echo "--dir-overflow-policy=spill --backstore-schema=h64 ${UBCC_OPTS:-}"
            ;;
        210|211|212|213|214|215|216|217|218|219|220|221|222|223|224|225|226|227)
            case "${EP_PERF_PROFILE:-optimized}" in
                naive) echo "--bloom-bytes=128 --sram-bytes=4352 --ways=1 --set-bits=0 --dir-overflow-policy=naive --batch-rs=0 ${UBCC_OPTS:-}" ;;
                spill-noopt) echo "--bloom-bytes=128 --sram-bytes=4352 --ways=1 --set-bits=0 --dir-overflow-policy=spill --batch-rs=0 ${UBCC_OPTS:-}" ;;
                optimized|*) echo "--bloom-bytes=128 --sram-bytes=4352 --ways=1 --set-bits=0 --dir-overflow-policy=spill --batch-rs=1 ${UBCC_OPTS:-}" ;;
            esac
            ;;
        228|229|230|231|232|233|234|235)
            if [ "$L3_PRESSURE_LEVEL" != 0 ] || [ -n "$L3_PRESSURE_TARGET_LINES" ]; then
                echo "--bloom-bytes=61440 --sram-bytes=524288 --ways=0 --set-bits=0 --dir-overflow-policy=spill --batch-rs=0 ${UBCC_OPTS:-}"
                return
            fi
            echo "${UBCC_OPTS:-}"
            ;;
        98)  echo "--ways=1" ;;
        *)   echo "" ;;
    esac
}

