# Kill any leftover infra from a previous TC / abort.
_kill_pid_tree() {
    # Commands are launched through a shell wrapper so killing only the wrapper
    # can leave its eval-launched gem5/UBIO child alive. Walk only descendants
    # of the explicitly recorded PID; never perform a name-based kill.
    local pid="$1" child
    [ -n "$pid" ] || return
    for child in $(pgrep -P "$pid" 2>/dev/null || true); do
        _kill_pid_tree "$child"
    done
    kill -TERM "$pid" 2>/dev/null || true
    sleep 0.1
    kill -KILL "$pid" 2>/dev/null || true
}

_kill_infra() {
    # Every PID is recorded by this runner for the current TC. Never use a
    # name-based kill here: another user run may share the host.
    for pid in ${GEM5_PIDS:-} ${UBIO_PIDS:-} ${NSIM_PID:-} ${SUPERVISOR_PID:-}; do
        _kill_pid_tree "$pid"
    done
    if [ -n "${MEMORY_MONITOR_PID:-}" ]; then
        kill "$MEMORY_MONITOR_PID" 2>/dev/null || true
        MEMORY_MONITOR_PID=""
    fi
    if [ -n "${SUPERVISOR_PID:-}" ]; then
        kill "$SUPERVISOR_PID" 2>/dev/null || true
        SUPERVISOR_PID=""
    fi
    for pid in ${GEM5_PIDS:-} ${UBIO_PIDS:-} ${NSIM_PID:-}; do
        wait "$pid" 2>/dev/null || true
    done
    sleep 0.3
    GEM5_PIDS=""; UBIO_PIDS=""; NSIM_PID=""
}
